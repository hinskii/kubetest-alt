package test

import (
	"errors"
	"os"
	"path/filepath"
)

// findRepoRoot walks upward from cwd looking for a go.mod. This lets tests
// reference paths like "config/crd/bases" regardless of which package the
// test runs from.
func findRepoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("go.mod not found walking up from cwd")
		}
		dir = parent
	}
}
