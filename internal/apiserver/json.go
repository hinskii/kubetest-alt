package apiserver

import (
	"encoding/json"
	"net/http"
)

// writeJSON serializes v as JSON with the correct content type + status.
// Errors during encoding are logged to the response body if the header
// hasn't been written yet; otherwise silently dropped (client already
// received partial bytes, nothing useful to do).
func writeJSON(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(v)
}
