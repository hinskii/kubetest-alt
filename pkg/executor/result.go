package executor

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
)

// WriteResultAtomic serializes result to $dir/result.json using a temp+rename
// dance. Readers never observe a partially-written file: os.Rename within a
// single filesystem is atomic per POSIX.
//
// Rationale for atomicity: SIGTERM handling. The wrapper flushes a partial
// result on signal, then exits. If we wrote result.json in-place with a truncate
// followed by write, a reader that opened between truncate and write would see
// an empty (invalid JSON) file. Temp+rename keeps the invariant "result.json,
// if present, is always valid JSON".
//
// dir must already exist (the operator mounts an emptyDir there at
// $KUBETEST_RESULTDIR). The temp file lives in the same directory so rename
// stays cross-inode-only, not cross-filesystem.
func WriteResultAtomic(dir string, result ExecutionResult) error {
	b, err := json.MarshalIndent(result, "", "  ")
	if err != nil {
		return fmt.Errorf("marshal result: %w", err)
	}

	// #nosec G304 -- dir is a controlled path (env var $KUBETEST_RESULTDIR
	// set by the operator); temp filename is generated by CreateTemp.
	tmp, err := os.CreateTemp(dir, ".result.json.*")
	if err != nil {
		return fmt.Errorf("create temp in %s: %w", dir, err)
	}
	tmpName := tmp.Name()
	// From here on, ensure the temp gets cleaned up on any error.
	cleanup := func() { _ = os.Remove(tmpName) }

	if _, err := tmp.Write(b); err != nil {
		_ = tmp.Close()
		cleanup()
		return fmt.Errorf("write temp: %w", err)
	}
	if err := tmp.Sync(); err != nil {
		_ = tmp.Close()
		cleanup()
		return fmt.Errorf("sync temp: %w", err)
	}
	if err := tmp.Close(); err != nil {
		cleanup()
		return fmt.Errorf("close temp: %w", err)
	}

	final := filepath.Join(dir, ResultFileName)
	if err := os.Rename(tmpName, final); err != nil {
		cleanup()
		return fmt.Errorf("rename to %s: %w", final, err)
	}
	return nil
}
